void SampleDio(void) {

    /*
     * 3.2.3 Dio module sample function
     */

    /* Execute channel reading */
    SampleDio_Level = Dio_ReadChannel( DioConf_DioChannel_DioChannel_Sw );

    /* Execute channel writing */
    Dio_WriteChannel( DioConf_DioChannel_DioChannel_LED1, STD_HIGH );

    /* End of program */
    while ( TRUE ) {
        FUNC_NO_OPERATION;
    }
}
