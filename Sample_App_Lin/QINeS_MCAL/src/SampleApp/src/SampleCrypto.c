static bool_t crypto_compareData( const uint8* paramA, const uint8* paramB, uint32 length )
{
    bool_t result = TRUE;
    uint32_least index;

    for ( index = 0x0U; index < length; index++ ) {
        if ( paramA[index] != paramB[index] ) {
            result = FALSE;
            break;
        }
    }
    return result;
}

